import fs from 'node:fs';import crypto from 'node:crypto';import assert from 'node:assert/strict';
import {readEntry,moviePack} from '../mod-tools/pack.mjs';
const here=new URL('./',import.meta.url),token=process.argv[2];
assert(/^[0-9a-f]{64}$/.test(token??''),'Pass the pending-marker token (64 lowercase hex characters)');
const original=readEntry(process.argv[3]??'D:/Steam/steamapps/common/Total War WARHAMMER III/data/@n_SlaaneshVictories.pack','script\\campaign\\mod\\@n_slaaneshvictories_script.lua');
const source=original.toString('utf8');
const anchor='            -- Check for each lord if their faction is corrupted or if they were defeated during AI turn';
assert.equal(source.split(anchor).length,2);
const injection=fs.readFileSync(new URL('injection.lua',here),'utf8').replace(/^\uFEFF/,'').replace(/\r\n/g,'\n').trimEnd()+'\n\n';
assert.equal(injection.split('__SAVE_TOKEN__').length,2);
const replacement=injection.replace('__SAVE_TOKEN__',token);
const candidate=Buffer.from(source.replace(anchor,replacement+anchor));
assert.equal(candidate.toString('utf8').replace(replacement,''),source);
fs.mkdirSync(new URL('.build-cache/',here),{recursive:true});
fs.writeFileSync(new URL('.build-cache/candidate.lua',here),candidate);
const path='script\\campaign\\mod\\@n_slaaneshvictories_script.lua';
const pack=moviePack(new Map([[path,candidate]]));
fs.writeFileSync(new URL('turn75_corruption_events.pack',here),pack);
const sha256=crypto.createHash('sha256').update(pack).digest('hex');
fs.writeFileSync(new URL('verification.json',here),JSON.stringify({sha256,originalSha256:crypto.createHash('sha256').update(original).digest('hex'),pendingToken:token,turn:76,type:'Movie',inGameVerified:false},null,2)+'\n');
console.log('Next-turn events SHA256 '+sha256);
